#!/usr/bin/env python3
"""Generates the CPU page's build alone (notes/78, tools/machines/cpu/): composes the builder's part cpu through
tools/compose.py, with no package, into tweaks/model-cycles_OS1.13/78-cpu.json: the card's build alone, which the web
flasher composes in the page with the machines, effects and Track FX ticked (its excludes come from that tweak's
conflicts). The part's object itself is built by tools/gen_parts.py (m68k toolchain); this generator needs python3
alone.

    python3 tools/gen_cpu.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

OUT = compose.DEV / "78-cpu.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed tweak matches")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    tweak, info = compose.compose(img, [], cpu=True)
    tweak["description"].append("Generated by tools/gen_cpu.py through tools/compose.py (notes/78).")
    bad = bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    c = info["cpu"]
    print(f"  cpu: {len(tweak['writes'])} writes, code {c['code']} bytes at {c['code_at']:#x}, data {c['data']} bytes, "
          f"{info['image']} bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
