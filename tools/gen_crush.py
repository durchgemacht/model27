#!/usr/bin/env python3
"""Generates Crush, a sample-rate and bit reduction as effect 2 of the Track FX (the filter slot, notes/73,
tools/machines/crush/): writes its table of clock steps into tools/machines/crush/crush_tab.h, compiles crush.c with
the manifest's recipe into tools/machines/crush/crush.o (ld -r, notes/60 §2), then composes it alone through
tools/compose.py, which places that object with tools/relocate.py as any build does, into
tweaks/model-cycles_OS1.13/73-crush.json: the card's build alone, which the web flasher composes in the page (its
excludes come from that tweak's conflicts). Needs the m68k toolchain (for the object); the table and compose.py do
not.

    python3 tools/gen_crush.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

PACKAGE = "crush"
TABLE = compose.MACHINES / PACKAGE / "crush_tab.h"
OUT = compose.DEV / "73-crush.json"
STEPS = 64                         # Rate's a, 0 .. 64 (8.8 in the word)
OCTAVES = 6                        # at a = 64 one frame in 2^6 = 64


def table():
    """CRUSH_INC[k] = 65536 / 2^(6k/64), k = 0 .. 64: the clock's step a frame at Rate k."""
    inc = [round(65536 * 2 ** (-OCTAVES * k / STEPS)) for k in range(STEPS + 1)]
    rows = [", ".join(f"{v:5d}" for v in inc[i:i + 8]) for i in range(0, len(inc), 8)]
    return ("/* Crush's clock (notes/73 §3.2), written by tools/gen_crush.py: CRUSH_INC[k] = round(65536 / 2^(6k/64)), the\n"
            " * clock's step a frame at Rate k (k = |word - 0x4000| >> 8, 0 .. 64): one frame taken in 2^(6k/64). */\n"
            "#ifndef CRUSH_TAB_H\n#define CRUSH_TAB_H\n#include <stdint.h>\n\n"
            "static const uint32_t CRUSH_INC[65] = {\n\t" + ",\n\t".join(rows) + "\n};\n\n#endif\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed table, object and tweak match")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    bad = bool(gm.emit(TABLE, table(), args.check))
    m = compose.load_manifest(PACKAGE)
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad |= bool(compose.emit_bytes(compose.object_path(m), obj, args.check))
    tweak, info = compose.compose(img, [PACKAGE])
    tweak["description"].append("Generated by tools/gen_crush.py through tools/compose.py (notes/73).")
    bad |= bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    p, f = info["packages"][0], info["filters"]
    print(f"  {PACKAGE}: {len(tweak['writes'])} writes, code and table {p['code']} bytes, variables {p['bss']} bytes, "
          f"the filter slot {f['code'] + f['data']} bytes, {info['image']} bytes added to the image, "
          f"{len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
