#!/usr/bin/env python3
"""Generates Samples, the Model:Samples' filter as filter 1 of the filter slot (the track filters, the key map's step
K4, tools/machines/smpfilter/): compiles its sources (its glue and SAMPLE's filter, tools/machines/sampler/src/) with
the manifest's recipe into tools/machines/smpfilter/smpfilter.o (ld -r of the objects, notes/60 §2), then composes it
alone through tools/compose.py, which places that object with tools/relocate.py as any build does, into
tweaks/model-cycles_OS1.13/72-smpfilter.json: the card's build alone, which the web flasher composes in the page (its
excludes come from that tweak's conflicts; step T5). Needs the m68k toolchain (for the object); compose.py alone does
not.

    python3 tools/gen_smpfilter.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

PACKAGE = "smpfilter"
OUT = compose.DEV / "72-smpfilter.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed object matches")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    m = compose.load_manifest(PACKAGE)
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad = bool(compose.emit_bytes(compose.object_path(m), obj, args.check))
    tweak, info = compose.compose(img, [PACKAGE])
    tweak["description"].append("Generated by tools/gen_smpfilter.py through tools/compose.py (the key map's step K4).")
    bad |= bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    p, f = info["packages"][0], info["filters"]
    print(f"  {PACKAGE}: {len(tweak['writes'])} writes, code and table {p['code']} bytes, variables {p['bss']} bytes, "
          f"the filter slot {f['code'] + f['data']} bytes, {info['image']} bytes added to the image, "
          f"{len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
