#!/usr/bin/env python3
"""Generates Ring, a ring modulator as effect 3 of the Track FX (the filter slot, notes/74, tools/machines/ring/):
writes its tables (the carrier's phase steps by note, its cosine) into tools/machines/ring/ring_tab.h, compiles ring.c
with the manifest's recipe into tools/machines/ring/ring.o (ld -r, notes/60 §2), then composes it alone through
tools/compose.py, which places that object with tools/relocate.py as any build does, into
tweaks/model-cycles_OS1.13/74-ring.json: the card's build alone, which the web flasher composes in the page (its
excludes come from that tweak's conflicts). Needs the m68k toolchain (for the object); the tables and compose.py do
not.

    python3 tools/gen_ring.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import math
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

PACKAGE = "ring"
TABLE = compose.MACHINES / PACKAGE / "ring_tab.h"
OUT = compose.DEV / "74-ring.json"
RATE = 48000                       # the audio's frames a second
NOTES = 128                        # Freq's value, a MIDI note 0 .. 127 (8.8 in the word), and one step after it
STEPS = 2048                       # the carrier's cosine, one period, not interpolated (since 0.3: 256 before)
FULL = 32767                       # its peak in Q15


def rows(values, width, per):
    return ",\n\t".join(", ".join(f"{v:{width}d}" for v in values[i:i + per]) for i in range(0, len(values), per))


def table():
    """RING_INC[n] = 2^32 f(n) / 48 kHz, f(n) = 440 * 2^((n - 69) / 12), n = 0 .. 128: the phase's step a frame at
    note n; RING_COS[i] = 32767 cos(2 pi (i + 1/2) / 2048), i = 0 .. 2047: the carrier, each step's value at its
    middle, so that the phase's top 11 bits pick it without interpolation and its peak is at phase 0 (notes/74 §13)."""
    inc = [round(2 ** 32 * 440 * 2 ** ((n - 69) / 12) / RATE) for n in range(NOTES + 1)]
    cos = [round(FULL * math.cos(2 * math.pi * (i + 0.5) / STEPS)) for i in range(STEPS)]
    return ("/* Ring's tables (notes/74 §3), written by tools/gen_ring.py.\n"
            " * RING_INC[n] = round(2^32 * 440 * 2^((n - 69) / 12) / 48000): the carrier's phase step a frame at Freq n\n"
            " * (n = word >> 8, a MIDI note 0 .. 127, and the step after the last). RING_COS[i] = round(32767 cos(2 pi\n"
            " * (i + 1/2) / 2048)): the carrier, a period in 2048 steps, each at its middle, read without interpolation\n"
            " * (the phase's top 11 bits), its peak at phase 0. */\n"
            "#ifndef RING_TAB_H\n#define RING_TAB_H\n#include <stdint.h>\n\n"
            f"static const uint32_t RING_INC[{NOTES + 1}] = {{\n\t" + rows(inc, 10, 6) + "\n};\n\n"
            f"static const int16_t RING_COS[{STEPS}] = {{\n\t" + rows(cos, 6, 10) + "\n};\n\n#endif\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed tables, object and tweak match")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    bad = bool(gm.emit(TABLE, table(), args.check))
    m = compose.load_manifest(PACKAGE)
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad |= bool(compose.emit_bytes(compose.object_path(m), obj, args.check))
    tweak, info = compose.compose(img, [PACKAGE])
    tweak["description"].append("Generated by tools/gen_ring.py through tools/compose.py (notes/74).")
    bad |= bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    p, f = info["packages"][0], info["filters"]
    print(f"  {PACKAGE}: {len(tweak['writes'])} writes, code and tables {p['code']} bytes, variables {p['bss']} bytes, "
          f"the filter slot {f['code'] + f['data']} bytes, {info['image']} bytes added to the image, "
          f"{len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
