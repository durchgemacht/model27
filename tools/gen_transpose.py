#!/usr/bin/env python3
"""Generates Transpose's build alone (notes/80, tools/machines/transpose/): composes the builder's part transpose
through tools/compose.py, with no package, into tweaks/model-cycles_OS1.13/81-transpose.json: the card's build alone,
which the web flasher composes in the page with the machines, effects, Track FX, the CPU page and RESAMPLE ticked (its
excludes come from that tweak's conflicts). The build always holds the shortcut layer, MACHINES a held key on every
track (the layer's 0.6). The part's object itself is built by tools/gen_parts.py (m68k toolchain); this generator
needs python3 alone.

    python3 tools/gen_transpose.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

OUT = compose.DEV / "81-transpose.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed tweak matches")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    tweak, info = compose.compose(img, [], transpose=True)
    tweak["description"].append("Generated by tools/gen_transpose.py through tools/compose.py (notes/80).")
    bad = bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    t, layer = info["transpose"], info["part"]
    print(f"  transpose: {len(tweak['writes'])} writes, code {t['code']} bytes at {t['code_at']:#x}, data {t['data']} "
          f"bytes, the shortcut layer at {layer['code_at']:#x}, a dimming period of {t['n']} ms, {info['image']} bytes "
          f"added to the image, {len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
