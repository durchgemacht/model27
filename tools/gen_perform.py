#!/usr/bin/env python3
"""Generates Perform Kit's build alone (notes/81, tools/machines/perform/): composes the builder's part perform
through tools/compose.py, with no package, into tweaks/model-cycles_OS1.13/82-perform.json: the card's build alone,
which the web flasher composes in the page with the machines, effects, Track FX, the CPU page, RESAMPLE and Transpose
ticked (its excludes come from that tweak's conflicts). Alone the part keeps SETTINGS' state itself (the key code
accessor 0x4007240c) and the stock main draw is behind its mark. The part's object itself is built by
tools/gen_parts.py (m68k toolchain); this generator needs python3 alone.

    python3 tools/gen_perform.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

OUT = compose.DEV / "82-perform.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed tweak matches")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    tweak, info = compose.compose(img, [], perform=True)
    tweak["description"].append("Generated by tools/gen_perform.py through tools/compose.py (notes/81).")
    bad = bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    p = info["perform"]
    print(f"  perform: {len(tweak['writes'])} writes, code {p['code']} bytes at {p['code_at']:#x}, data {p['data']} bytes, "
          f"SETTINGS' state kept by {p['held_by']}, the main draw behind its mark: {p['main_behind']}, {info['image']} "
          f"bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
