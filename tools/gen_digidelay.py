#!/usr/bin/env python3
"""Generates Digital Delay, PPPCCC's digital delay as an effect of the delay slot (notes/68 §18, §19,
tools/machines/digidelay/): compiles its sources with the manifest's recipe into tools/machines/digidelay/digidelay.o
(ld -r of the objects, notes/60 §2), then composes it alone through tools/compose.py, which places that object with
tools/relocate.py as any build does, into tweaks/model-cycles_OS1.13/39-digidelay.json: the card's build alone, which
the web flasher composes in the page (its excludes come from that tweak's conflicts); and PPPCCC's MIT text into
tweaks/model-cycles_OS1.13/LICENSE-PPPCCC, which the page serves next to the card. Needs the m68k toolchain (for the
object); compose.py alone does not.

    python3 tools/gen_digidelay.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

PACKAGE = "digidelay"
OUT = compose.DEV / "39-digidelay.json"
LICENSE_OUT = compose.DEV / "LICENSE-PPPCCC"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed object and tweak match")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    m = compose.load_manifest(PACKAGE)
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad = bool(compose.emit_bytes(compose.object_path(m), obj, args.check))
    bad |= bool(gm.emit(LICENSE_OUT, (m["_dir"] / "LICENSE").read_text(encoding="utf-8"), args.check))
    tweak, info = compose.compose(img, [PACKAGE])
    tweak["description"].append("Generated by tools/gen_digidelay.py through tools/compose.py (notes/68 §18).")
    bad |= bool(gm.emit(OUT, json.dumps(tweak, indent=1, ensure_ascii=False) + "\n", args.check))
    p = info["packages"][0]
    at, n = info["fx_lines"]["fx.delay"]
    print(f"  {PACKAGE}: {len(tweak['writes'])} writes, code {p['code']} bytes, variables {p['bss']} bytes, the "
          f"delay slot's line {n} bytes at {at:#x}, {info['image']} bytes added to the image, "
          f"{len(tweak['conflicts'])} conflicts computed")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
