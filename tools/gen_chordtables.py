#!/usr/bin/env python3
"""Generates the tweak of CHORD Tables alone: 36-chordtables.json (notes/66).

CHORD Tables (tools/machines/chordtables/) extends the stock CHORD machine instead of adding one: RETRIG + SWEEP picks
a wavetable, 0 the stock one, 1 to 64 the files /Wavetables/01 to /Wavetables/64 on the +Drive, loaded on the screen's
tick. This generator compiles the package's sources with the manifest's recipe into its committed object
(tools/machines/chordtables/chordtables.o, ld -r of the objects: notes/60 §2), then composes it alone through
tools/compose.py, which places that object with tools/relocate.py as any build does (nothing registered: no added
machine, notes/66 §3). It writes the result into tweaks/ so that check_overlaps.py, registry.py and
build.py -t chordtables see it. Needs the m68k toolchain (for the object); compose.py alone does not.

    python3 tools/gen_chordtables.py --cycles model-cycles_OS1.13.syx [--check]
"""
import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import compose                     # noqa: E402
import gen_macro as gm             # noqa: E402
import gen_sdvintage_exact as gx   # noqa: E402
import gen_sdvintage_7th as g7     # noqa: E402

ID = "chordtables"
OUT = compose.DEV / "36-chordtables.json"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cycles", required=True, help="official model-cycles_OS1.13.syx")
    ap.add_argument("--check", action="store_true", help="checks that the committed files match")
    args = ap.parse_args()
    img = g7.cycles_main(args.cycles)
    if len(img) != gx.IMAGE_LEN:
        raise SystemExit("!! not the official MAIN OS 1.13")
    m = compose.load_manifest(ID)
    with tempfile.TemporaryDirectory() as d:
        obj = compose.build_object(m, pathlib.Path(d))
    bad = bool(compose.emit_bytes(compose.object_path(m), obj, args.check))
    tweak, info = compose.compose(img, [ID])
    tweak["description"].append("Generated by tools/gen_chordtables.py through tools/compose.py (notes/66).")
    text = json.dumps(tweak, indent=1, ensure_ascii=False) + "\n"
    p = info["packages"][0]
    print(f"  {ID}: {len(tweak['writes'])} writes, code {p['code']} bytes, variables {p['bss']} bytes, "
          f"{info['image']} bytes added to the image, {len(tweak['conflicts'])} conflicts computed")
    bad |= bool(gm.emit(OUT, text, args.check))
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
